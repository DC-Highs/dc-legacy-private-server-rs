CREATE TABLE IF NOT EXISTS friendships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    low_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    high_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    requester_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    status VARCHAR(16) NOT NULL DEFAULT 'accepted',
    created_at TIMESTAMPTZ NOT NULL,
    responded_at TIMESTAMPTZ,
    CONSTRAINT uq_friendship_pair UNIQUE (low_id, high_id),
    CONSTRAINT ck_friendship_ordered CHECK (low_id < high_id)
);
CREATE INDEX IF NOT EXISTS ix_friendships_low_id ON friendships (low_id);
CREATE INDEX IF NOT EXISTS ix_friendships_high_id ON friendships (high_id);
